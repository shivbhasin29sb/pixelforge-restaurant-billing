package com.pixelforge.restaurant.model;

import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

/**
 * ============================================================
 * MODEL CLASS: Bill
 * ============================================================
 * Represents a finalised restaurant bill generated when a
 * customer is ready to check out.
 *
 * A Bill captures:
 *   - Which table it belongs to
 *   - A formatted text of all ordered items (billDetails)
 *   - Financial breakdown: subtotal, GST (5%), grand total
 *   - The exact timestamp when the bill was generated
 *
 * TWO CONSTRUCTORS:
 * We provide two constructors for two different use cases:
 *
 *   1) Creating a NEW bill (no billId yet — the DB auto-generates it):
 *      Bill(tableId, billDetails, subtotal, gst, grandTotal, billTime)
 *
 *   2) Loading an EXISTING bill FROM the database (billId is known):
 *      Bill(billId, tableId, billDetails, subtotal, gst, grandTotal, billTime)
 *
 * GST (Goods and Services Tax):
 *   In India, restaurant services attract 5% GST.
 *   grandTotal = subtotal + (subtotal × 0.05)
 * ============================================================
 */
public class Bill {

    private int billId;            // Auto-generated by the database (0 for new bills)
    private int tableId;           // Table this bill was generated for
    private String billDetails;    // Formatted text listing all ordered items
    private double subtotal;       // Total before tax
    private double gst;            // GST amount (5% of subtotal)
    private double grandTotal;     // Final amount customer pays (subtotal + gst)
    private LocalDateTime billTime; // Date and time the bill was generated

    // ============================================================
    // CONSTRUCTOR 1: For creating a NEW bill
    // (billId not provided — the DB will assign it after INSERT)
    // ============================================================

    /**
     * Use this constructor when generating a fresh bill for checkout.
     * The billId will be 0 (default int value) until the DB assigns one.
     *
     * @param tableId     The table being billed
     * @param billDetails The formatted string of all items ordered
     * @param subtotal    The pre-tax total in ₹
     * @param gst         The GST amount in ₹ (5% of subtotal)
     * @param grandTotal  The final total (subtotal + gst) in ₹
     * @param billTime    The timestamp when the bill was generated
     */
    public Bill(int tableId, String billDetails, double subtotal,
                double gst, double grandTotal, LocalDateTime billTime) {
        this.billId      = 0;  // Will be set after DB auto-generates it
        this.tableId     = tableId;
        this.billDetails = billDetails;
        this.subtotal    = subtotal;
        this.gst         = gst;
        this.grandTotal  = grandTotal;
        this.billTime    = billTime;
    }

    // ============================================================
    // CONSTRUCTOR 2: For loading an EXISTING bill from the DB
    // (billId is already known from the database record)
    // ============================================================

    /**
     * Use this constructor when retrieving a bill record from the database.
     * All fields including billId are set.
     *
     * @param billId      The unique bill ID from the database
     * @param tableId     The table this bill was generated for
     * @param billDetails The formatted string of all items ordered
     * @param subtotal    The pre-tax total in ₹
     * @param gst         The GST amount in ₹
     * @param grandTotal  The final total in ₹
     * @param billTime    The timestamp when the bill was generated
     */
    public Bill(int billId, int tableId, String billDetails, double subtotal,
                double gst, double grandTotal, LocalDateTime billTime) {
        this.billId      = billId;
        this.tableId     = tableId;
        this.billDetails = billDetails;
        this.subtotal    = subtotal;
        this.gst         = gst;
        this.grandTotal  = grandTotal;
        this.billTime    = billTime;
    }

    // ============================================================
    // GETTERS
    // ============================================================

    /** Returns the bill's unique ID (assigned by the database). */
    public int getBillId() {
        return billId;
    }

    /** Returns the table ID this bill was generated for. */
    public int getTableId() {
        return tableId;
    }

    /** Returns the formatted text listing all ordered items. */
    public String getBillDetails() {
        return billDetails;
    }

    /** Returns the subtotal (pre-tax) in ₹. */
    public double getSubtotal() {
        return subtotal;
    }

    /** Returns the GST amount (5% of subtotal) in ₹. */
    public double getGst() {
        return gst;
    }

    /** Returns the grand total (subtotal + GST) in ₹. */
    public double getGrandTotal() {
        return grandTotal;
    }

    /** Returns the timestamp when the bill was generated. */
    public LocalDateTime getBillTime() {
        return billTime;
    }

    // ============================================================
    // SETTERS
    // ============================================================

    /**
     * Sets the billId — typically called after the DB INSERT
     * returns the auto-generated ID.
     */
    public void setBillId(int billId) {
        this.billId = billId;
    }

    /** Sets the table ID. */
    public void setTableId(int tableId) {
        this.tableId = tableId;
    }

    /** Sets the formatted item details string. */
    public void setBillDetails(String billDetails) {
        this.billDetails = billDetails;
    }

    /** Sets the subtotal amount. */
    public void setSubtotal(double subtotal) {
        this.subtotal = subtotal;
    }

    /** Sets the GST amount. */
    public void setGst(double gst) {
        this.gst = gst;
    }

    /** Sets the grand total. */
    public void setGrandTotal(double grandTotal) {
        this.grandTotal = grandTotal;
    }

    /** Sets the timestamp when the bill was generated. */
    public void setBillTime(LocalDateTime billTime) {
        this.billTime = billTime;
    }

    // ============================================================
    // toString()
    // ============================================================

    /**
     * Returns a full formatted bill summary, like a printed receipt.
     *
     * Example output:
     * ========================================
     *       PixelForge Restaurant
     *         BILL #42 | Table #3
     *   Generated: 20-Nov-2024 07:45 PM
     * ----------------------------------------
     *   - Paneer Tikka x 2 = ₹440.00
     *   - Butter Naan x 3 = ₹120.00
     * ----------------------------------------
     *   Subtotal   :  ₹560.00
     *   GST (5%)   :   ₹28.00
     *   GRAND TOTAL:  ₹588.00
     * ========================================
     */
    @Override
    public String toString() {
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd-MMM-yyyy hh:mm a");
        String line = "----------------------------------------";
        String doubleLine = "========================================";

        return doubleLine + "\n"
             + "        PixelForge Restaurant\n"
             + "          BILL #" + billId + " | Table #" + tableId + "\n"
             + "  Generated: " + (billTime != null ? billTime.format(formatter) : "N/A") + "\n"
             + line + "\n"
             + billDetails + "\n"
             + line + "\n"
             + String.format("  Subtotal    : \u20B9%.2f%n", subtotal)
             + String.format("  GST (5%%)    : \u20B9%.2f%n", gst)
             + String.format("  GRAND TOTAL : \u20B9%.2f%n", grandTotal)
             + doubleLine;
    }
}
